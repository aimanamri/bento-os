'use strict';

// Mint the anon + service_role JWTs for the SELF-HOSTED stack (docker-compose).
//
//   node scripts/gen-local-keys.js [jwt-secret]
//
// In self-hosted Supabase there is no dashboard handing you API keys: the
// "anon key" and "service_role key" are just HS256 JWTs carrying a `role`
// claim, signed with the same JWT_SECRET you give GoTrue and PostgREST.
// PostgREST reads that claim and does `SET LOCAL ROLE <role>` for the
// transaction, which is what makes every RLS policy in supabase/migrations/
// apply exactly as it does on the hosted product.
//
// Run this whenever you change POSTGRES/JWT secrets — the three values must
// stay in sync or every request 401s:
//   .env                     JWT_SECRET, ANON_KEY, SERVICE_ROLE_KEY
//   src/js/supabase-config.js  SUPABASE_ANON_KEY
//
// No dependencies: HS256 is an HMAC, and Node ships one.

const crypto = require('crypto');

const DEFAULT_SECRET = 'bento-os-local-dev-jwt-secret-change-me-32b';

const secret = process.argv[2] || process.env.JWT_SECRET || DEFAULT_SECRET;
if (secret.length < 32) {
  console.error(`JWT secret must be at least 32 characters (got ${secret.length}).`);
  process.exit(1);
}

const b64url = (buf) =>
  Buffer.from(buf).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

function sign(payload) {
  const header = b64url(JSON.stringify({ alg: 'HS256', typ: 'JWT' }));
  const body = b64url(JSON.stringify(payload));
  const data = `${header}.${body}`;
  const sig = b64url(crypto.createHmac('sha256', secret).update(data).digest());
  return `${data}.${sig}`;
}

// Fixed iat/exp keep the output deterministic: the same secret always yields
// the same keys, so a rebuild never silently invalidates a committed config.
const IAT = 1767225600; // 2026-01-01
const EXP = 2082758400; // 2036-01-01

const anon = sign({ role: 'anon', iss: 'supabase', iat: IAT, exp: EXP });
const service = sign({ role: 'service_role', iss: 'supabase', iat: IAT, exp: EXP });

process.stdout.write(`# Generated by scripts/gen-local-keys.js
JWT_SECRET=${secret}
ANON_KEY=${anon}
SERVICE_ROLE_KEY=${service}
`);
